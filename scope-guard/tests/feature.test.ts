import { test, expect } from 'claude-code/testing'
import { Feature } from '../hooks/core/feature.ts'
const io = (status = '') => ({ cwd: '/repo', read: async () => '', run: async () => ({ exitCode: 0, stdout: status, stderr: '' }), env: async () => undefined, revision: async () => 'a' })
test('explicit path scopes accept descendants, reject prefix siblings and show both rename sides', async () => {
  const f = new Feature()
  await f.command('allow src/auth', io())
  const report = await f.command('', io(' M src/auth/a.ts\0 M src/authz/a.ts\0R  src/auth/new.ts\0src/old.ts\0'))
  expect(report).toContain('OUTSIDE src/authz/a.ts')
  expect(report).toContain('OUTSIDE src/old.ts')
  expect(report).not.toContain('OUTSIDE src/auth/a.ts')
})
test('scope entry rejects traversal and empty scopes do not pretend everything is permitted', async () => {
  const f = new Feature()
  expect(await f.command('allow ../outside', io())).toContain('Invalid')
  expect(await f.command('', io())).toContain('No scope')
  expect(await f.command('allow src/../../outside', io())).toContain('Invalid')
})
test('pre-existing files are labelled and observed out-of-repo writes are visible without blocking', async () => {
  const f = new Feature()
  await f.command('allow src', io(' M README.md\0'))
  await f.observe({ tool: 'Write', input: { file_path: '/elsewhere/private' }, result: { text: 'ok' } }, io())
  const report = await f.command('', io(' M README.md\0 M src/a.ts\0'))
  expect(report).toContain('PRE-EXISTING README.md')
  expect(report).toContain('OUTSIDE /elsewhere/private')
})
test('a capped pre-existing baseline stays explicitly incomplete after the live change list shrinks', async () => {
  const f = new Feature(), status = Array.from({ length: 201 }, (_, i) => ` M old-${i}.ts\0`).join('')
  await f.command('allow src', io(status))
  const report = await f.command('', io(' M old-0.ts\0'))
  expect(report).toContain('INCOMPLETE: pre-existing baseline')
  expect(report).toContain('BASELINE-UNKNOWN old-0.ts')
})
test('literal directory scopes preserve repeated spaces in real path names', async () => {
  const f = new Feature()
  await f.command('allow src/auth  service', io())
  const report = await f.command('', io(' M src/auth  service/a.ts\0 M src/auth service/a.ts\0'))
  expect(report).toContain('IN-SCOPE src/auth  service/a.ts')
  expect(report).toContain('OUTSIDE src/auth service/a.ts')
})
test('root scope includes project files but never outside writes and denied edits leave no trace', async () => {
  const f = new Feature()
  await f.command('allow .', io())
  await f.observe({ tool: 'Write', input: { file_path: '/outside/file.ts' }, result: { text: 'ok' } }, io())
  await f.observe({ tool: 'Edit', input: { file_path: '/repo/denied.ts' }, result: { deny: 'no' } }, io())
  const report = await f.command('', io(' M nested/file.ts\0'))
  expect(report).toContain('IN-SCOPE nested/file.ts')
  expect(report).toContain('OUTSIDE /outside/file.ts')
  expect(report).not.toContain('denied.ts')
})
